#!/usr/bin/env bash
#
# Encrypted database backup, verified, 30-day retention, newest copied to R2.
# Runs inside the clipupp-backup container nightly. By hand, run the same thing in the container:
#   docker exec clipupp-backup clipupp-backup
# or on the host (needs rclone there for the off-site copy):
#   scripts/backup.sh
#
# Exit status: 0 only when the dump is written, verified AND copied off-site; then the epoch
# seconds of the run are written to <backups>/.last-backup-ok, which healthcheck-notify.sh
# watches. 1 when the dump fails. 3 when the dump is fine but the off-site copy failed, or
# BACKUP_BUCKET is set and rclone is missing.
set -euo pipefail
cd "$(dirname "$0")/.." 2>/dev/null || true
# .env is generated by render-env.sh with single-quoted values: parse it literally instead of
# sourcing and strip the quotes. Inside the container the variables arrive through the compose
# environment and .env is absent.
if [ -f .env ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      ''|'#'*) continue ;;
      [A-Za-z_]*=*)
        val="${line#*=}"
        case "$val" in \'*\') val="${val#\'}"; val="${val%\'}" ;; esac
        export "${line%%=*}=$val" ;;
    esac
  done < .env
fi
KEY="${BACKUP_KEY_FILE:-$([ -f /keys/backup.key ] && echo /keys/backup.key || echo .backup-key)}"
OUT_DIR="${BACKUP_DIR:-$([ -d /backups ] && echo /backups || echo backups)}"
RETAIN="${BACKUP_RETAIN_DAYS:-30}"
FILE="$OUT_DIR/clipupp-$(date -u +%Y%m%d-%H%M%S).sql.gz.enc"
enc() { openssl enc -aes-256-cbc -pbkdf2 -iter 200000 -salt -pass "file:$KEY"; }
dec() { openssl enc -d -aes-256-cbc -pbkdf2 -iter 200000 -pass "file:$KEY"; }
if [ -n "${PGHOST:-}" ]; then
  # In the container PGHOST, PGUSER, PGPASSWORD and PGDATABASE come from the compose environment.
  dump() { pg_dump --no-owner --no-privileges; }
else
  dump() { docker exec "${DB_CONTAINER:-${CONTAINER_PREFIX:-clipupp}-db}" pg_dump -U "$DB_USERNAME" --no-owner --no-privileges clipupp_db; }
fi
mkdir -p "$OUT_DIR"
if dump | gzip -9 | enc > "$FILE" && dec < "$FILE" | gzip -t && [ "$(wc -c < "$FILE")" -gt 1024 ]; then
  chmod 600 "$FILE"; echo "[backup] wrote $FILE ($(du -h "$FILE" | cut -f1))"
else
  echo "[backup] FAILED" >&2; rm -f "$FILE"; exit 1
fi
offsite=ok
if [ -n "${BACKUP_BUCKET:-}" ]; then
  if ! command -v rclone >/dev/null 2>&1; then
    echo "[backup] off-site copy NOT made: BACKUP_BUCKET is set but rclone is not installed" >&2
    offsite=failed
  elif rclone copyto "$FILE" "r2:${BACKUP_BUCKET}/$(basename "$FILE")" --s3-no-check-bucket -q; then
    echo "[backup] copied to r2:${BACKUP_BUCKET}"
  else
    echo "[backup] off-site copy FAILED" >&2
    offsite=failed
  fi
else
  echo "[backup] BACKUP_BUCKET not set; local copy only"
fi
find "$OUT_DIR" -name 'clipupp-*.sql.gz.enc' -mtime "+$RETAIN" -delete
find "$OUT_DIR" -name 'pre-deploy-*.sql.gz.enc' -mtime "+$RETAIN" -delete
[ "$offsite" = ok ] || exit 3
date +%s > "$OUT_DIR/.last-backup-ok.tmp" && mv -f "$OUT_DIR/.last-backup-ok.tmp" "$OUT_DIR/.last-backup-ok"
